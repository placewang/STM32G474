void dma_print_hex(const uint8_t *data, uint16_t len) {
    // 等待上一次 DMA 发送完成
    while (HAL_UART_GetState(&huart2) & HAL_UART_STATE_BUSY_TX);

    static char hex_buffer[256];  // 足够大
    char *p = hex_buffer;
    for (uint16_t i = 0; i < len && (p - hex_buffer) < (int)sizeof(hex_buffer) - 4; i++) {
        p += sprintf(p, "%02X ", data[i]);
    }
    if (p > hex_buffer) {
        *(p-1) = '\n';  // 替换最后一个空格为换行
        *p = '\0';
    } else {
        hex_buffer[0] = '\0';
    }

    HAL_UART_Transmit_DMA(&huart2, (uint8_t*)hex_buffer, strlen(hex_buffer));
}
